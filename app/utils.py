"""Небольшие вспомогательные функции общего назначения."""


def plural_ru(number, one, few, many):
    """Возвращает нужную форму русского существительного для заданного числа.

    Примеры:
        plural_ru(1, "задание", "задания", "заданий")  -> "задание"
        plural_ru(2, "задание", "задания", "заданий")  -> "задания"
        plural_ru(5, "задание", "задания", "заданий")  -> "заданий"
        plural_ru(11, "задание", "задания", "заданий") -> "заданий"
        plural_ru(21, "задание", "задания", "заданий") -> "задание"
    """
    n = abs(int(number)) % 100
    n1 = n % 10

    if 11 <= n <= 14:
        return many
    if n1 == 1:
        return one
    if 2 <= n1 <= 4:
        return few
    return many
